double palette::factors[scale][scale];

palette::palette() {
  std::array<double, channels> r;
  r.fill(0.);
  for (int w = min_wl; w < max_wl; ++w) {
    int l = channels * (w - min_wl) / (max_wl - min_wl);
    r[l] += Color::toY(w);
  }
  for (int y = 0; y < scale; ++y) {
    for (int x = 0; x < scale; ++x) {
      int val = compact_sp[y][x];
      double f = 0;
      for (int l = 0; l < channels; ++l) {
        f += (3 & (val >> (2 * l))) * r[l];
      }
      factors[y][x] = f ? 1. / f : 1.;
    }
  }
}

sampled_spectrum palette::geti(int x, int y, sampled_wl const &wl) {
  sampled_spectrum s;
  assert(0 <= x && x < scale && 0 <= y && y < scale);
  int csp = compact_sp[y][x];
  double invc = (double)channels / (max_wl - min_wl);
  for (int i = 0; i < nb_s; ++i) {
    int l = invc * (wl.lambda[i] - min_wl);
    s[i] = 3 & (csp >> (2 * l));
  }
  s *= factors[y][x];
  return s;
}

sampled_spectrum palette::get(double x, double y, sampled_wl const &wl) {
  x = x * scale;
  y = (1. - y) * scale;
  int xi = x, yi = y, xj = xi + 1, yj = yi + 1;
  double xf = x - xi, yf = y - yi;
  sampled_spectrum sp[4] = {
    geti(xi, yi, wl), geti(xj, yi, wl),
    geti(xi, yj, wl), geti(xj, yj, wl)
  };
  sampled_spectrum pi = (1. - xf) * sp[0] + xf * sp[1];
  sampled_spectrum pj = (1. - xf) * sp[2] + xf * sp[3];
  sampled_spectrum s = (1. - yf) * pi + yf * pj;
  for (int i = 0; i < nb_s; ++i) {
    if (s[i] > 1.) s[i] = 1.;
  }
  return s;
}

