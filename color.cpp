sampled_spectrum xyY::sample(point2 const &, sampled_wl const &wl) const {
  return strength * palette::get(x, y, wl);
}

sampled_spectrum fromXYZ(vec const &c, sampled_wl const &wl) {
  double t = c[0] + c[1] + c[2];
  if (t == 0.) return sampled_spectrum(0.);
  return c[1] * palette::get(c[0] / t, c[1] / t, wl);
}

sampled_spectrum from_texture::sample(point2 const &uv, sampled_wl const &wl) const {
  int x = std::min<int>(uv[0] * img->width, img->width - 1);
  int y = std::min<int>((1 - uv[1]) * img->height, img->height - 1);
  vec c = img->read(x, y);
  return fromXYZ(Color::RGBtoXYZ * c, wl);
}

